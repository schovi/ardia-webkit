import assert from "node:assert/strict";

export const ALLOWED_TEST = "a watch from someone not sharing turns sharing on for 14 days and tags every event";

export function assessTests(status, text) {
  const count = (name) => Number(text.match(new RegExp(`^# ${name} (\\d+)`, "m"))?.[1] ?? NaN);
  const tests = count("tests"), pass = count("pass"), fail = count("fail");
  assert.ok(tests > 0 && pass + fail === tests, "missing or inconsistent TAP totals");
  assert.equal(count("skipped"), 0, "JS tests were skipped");
  assert.equal(count("cancelled"), 0, "JS tests were cancelled");
  const failures = [...text.matchAll(/^not ok \d+ - ([^\n]+)\n([\s\S]*?)(?=^(?:ok |not ok |1\.\.|# tests )|(?![\s\S]))/gm)];
  assert.equal(failures.length, fail, "TAP failure count does not match totals");
  if (!fail) { assert.equal(status, 0); return `${pass}/${tests} JS tests; typecheck passed`; }
  assert.equal(status, 1, "unexpected test process status");
  assert.equal(fail, 1, "more than the single allowed JS failure");
  const [, name, detail] = failures[0];
  assert.equal(name, ALLOWED_TEST, "unexpected failing test");
  assert.match(detail, /src\/state\/telemetry\/watch\.test\.mjs/);
  assert.match(detail, /ERR_ASSERTION/);
  assert.match(detail, /expected: ['"]FB-1001['"]/);
  assert.match(detail, /operator: ['"]strictEqual['"]/);
  return `${pass}/${tests} JS tests; only allowed: ${ALLOWED_TEST}; typecheck passed`;
}

export function parseOptions(args, names) {
  const options = { build: true, rows: names };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--no-build") options.build = false;
    else if (args[i] === "--only") {
      const name = args[++i];
      assert.ok(names.includes(name), `unknown row: ${name}; choose ${names.join(", ")}`);
      assert.equal(options.rows, names, "--only can be specified once");
      options.rows = [name];
    } else throw new Error(`unknown option: ${args[i]}`);
  }
  return options;
}

export function standinMethods(sources) {
  const methods = new Map();
  for (const source of sources) {
    for (const implementation of source.matchAll(/@implementation\s+(\w+)(?:\s*\(\w+\))?([\s\S]*?)@end/g)) {
      const owner = implementation[1];
      for (const method of implementation[2].matchAll(/^[+-]\s*\([\s\S]*?(?=^[+-]\s*\(|(?![\s\S]))/gm)) {
        if (!method[0].includes('[standin]')) continue;
        const signature = method[0].split("{")[0].trim();
        let depth = 0, end = 0;
        for (let i = signature.indexOf("("); i < signature.length; i++) {
          if (signature[i] === "(") depth++;
          if (signature[i] === ")" && --depth === 0) { end = i + 1; break; }
        }
        const argumentsText = signature.slice(end);
        const parts = [...argumentsText.matchAll(/\b(\w+)\s*:/g)].map((part) => `${part[1]}:`);
        const selector = parts.length ? parts.join("") : argumentsText.trim().split(/\s/)[0];
        const key = `${signature[0]}[${owner} ${selector}]`;
        assert.ok(!methods.has(key), `duplicate stand-in: ${key}`);
        methods.set(key, owner);
      }
    }
  }
  return methods;
}

export function standinReport(sources, logs, rows) {
  const methods = standinMethods(sources), counts = new Map();
  for (const log of logs) {
    for (const hit of log.matchAll(/\[standin\]\s+([+-])\[(\w+)(?:\(\w+\))?\s+([^\]]+)\]/g)) {
      const key = `${hit[1]}[${hit[2]} ${hit[3]}]`;
      assert.ok(methods.has(key), `logged stand-in is missing from source inventory: ${key}`);
      counts.set(key, (counts.get(key) ?? 0) + 1);
    }
  }
  const out = ["# WebKit stand-ins", "", "Generated by `scripts/webkit/check`. Do not edit by hand.", "",
    `Rows: ${rows.map((row) => `\`${row}\``).join(", ")}.`, "",
    "A hit is a logged occurrence over all launches in this run. Each method logs once per process, not once per call.", "",
    `${methods.size} stand-ins; ${counts.size} hit; ${[...counts.values()].reduce((total, count) => total + count, 0)} logged hits.`, ""];
  for (const owner of [...new Set(methods.values())].sort()) {
    out.push(`## ${owner}`, "", "| Method | Hit | Count |", "|---|---|---:|");
    for (const key of [...methods.keys()].filter((key) => methods.get(key) === owner).sort()) {
      const count = counts.get(key) ?? 0;
      out.push(`| \`${key}\` | ${count ? "yes" : ""} | ${count} |`);
    }
    out.push("");
  }
  return out.join("\n");
}

export function screenIsLocked(value) {
  if (!value || typeof value !== "object") return false;
  if (value.CGSSessionScreenIsLocked) return true;
  return Object.values(value).some(screenIsLocked);
}

export function resultFails(status) {
  return !["PASS", "NEEDS PERSON", "SKIPPED (screen locked)"].includes(status);
}

export class RowOutcome extends Error {
  constructor(status, message) { super(message); this.resultStatus = status; }
}
